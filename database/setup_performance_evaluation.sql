-- Performance Evaluation module (Worker / Employee / Manager).
-- Run this in the Supabase SQL editor once.
-- Additive only; safe to re-run.

-- 1) Employee category + worker login ID
alter table public.employees add column if not exists category text not null default 'employee';
alter table public.employees add column if not exists employee_no text;

create unique index if not exists employees_employee_no_key
  on public.employees (employee_no)
  where employee_no is not null;

-- 2) Evaluation templates (sections + scored criteria, JSONB)
create table if not exists public.evaluation_templates (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'employee',
  department text,
  description text,
  sections jsonb not null default '[]'::jsonb,
  status text not null default 'active',
  created_by bigint,
  created_by_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists evaluation_templates_category_idx
  on public.evaluation_templates (category);

-- 3) Evaluation results generated from a template
create table if not exists public.evaluations (
  id bigint generated by default as identity primary key,
  template_id bigint references public.evaluation_templates(id) on delete set null,
  employee_id bigint not null,
  evaluator_id bigint,
  evaluator_name text,
  evaluator_role text,
  review_period text not null,
  status text not null default 'draft',
  scores jsonb not null default '{}'::jsonb,
  overall_score numeric not null default 0,
  employee_acknowledged boolean not null default false,
  employee_acknowledged_at timestamptz,
  acknowledged_by bigint,
  acknowledged_by_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists evaluations_employee_idx on public.evaluations (employee_id);
create index if not exists evaluations_template_idx on public.evaluations (template_id);

-- 4) Per-worker KPI rules (which template + criteria apply to an employee)
create table if not exists public.worker_evaluation_rules (
  id bigint generated by default as identity primary key,
  employee_id bigint not null unique,
  template_id bigint references public.evaluation_templates(id) on delete set null,
  criteria jsonb not null default '[]'::jsonb,
  active boolean not null default true,
  updated_by bigint,
  updated_by_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 5) Worker ID-only login sessions
create table if not exists public.worker_sessions (
  id bigint generated by default as identity primary key,
  employee_id bigint not null,
  token text not null unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists worker_sessions_token_idx on public.worker_sessions (token);
